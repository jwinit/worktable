const assert = require('node:assert/strict');
const vm = require('node:vm');
const fs = require('node:fs');
const context = {console,crypto:require('node:crypto').webcrypto};
vm.createContext(context);
for (const file of ['core','sprint-data','sprint-model']) vm.runInContext(fs.readFileSync('dist/'+file+'.js','utf8'),context);
const M=context.SprintModel,D=context.SprintData;
const state=M.initial(),date=state.start;
assert.equal(M.slots.reduce((sum,slot)=>sum+slot.minutes,0),120);
for(const [field,key,expected] of [['lang','en',70],['lang','ja',50],['period','am',80],['period','pm',40]])assert.equal(M.slots.filter(slot=>slot[field]===key).reduce((sum,slot)=>sum+slot.minutes,0),expected);
assert.equal(M.plan(state,date).day,1);
assert.equal(M.plan(state,M.shift(date,-1)).active,false);
assert.equal(M.plan(state,M.endDate(date)).active,false);
assert.equal(M.endDate('2026-08-31'),'2027-02-28');
assert.equal(M.statistics(state,[date]).en.total,0);
assert.equal(M.trainingPhase(state,'ja',M.shift(date,150)),0);
assert.ok(M.focus(state,'en',date).reason.includes('尚无'));
assert.equal(D.kana.length,46);
for(const lang of ['en','ja'])for(const unit of D[lang])for(const type of ['grammar','reading','listening']){
  assert.ok(unit[type][1][unit[type][2]]);
  assert.ok(unit[type][3].length>4);
}
let session=M.makeSession(state,M.slots[0],date);
state.sessions[session.id]=session;
const question=session.questions[0];
M.mark(state,session,question,'错误');
const key='en:'+question.id;
assert.equal(state.knowledge[key].next,M.shift(date,1));
assert.equal(state.knowledge[key].wrong,true);
assert.equal(M.mark(state,session,question,question.answer).correct,false,'Submitted answers must be immutable');
session=M.makeSession(state,M.slots[2],date);
state.sessions[session.id]=session;
M.mark(state,session,question,question.answer);
assert.equal(state.knowledge[key].stage,0,'Same-day repetitions do not expand interval');
session=M.makeSession(state,M.slots[0],M.shift(date,1));
state.sessions[session.id]=session;
M.mark(state,session,question,question.answer);
assert.equal(state.knowledge[key].stage,1);
assert.equal(state.knowledge[key].next,M.shift(date,3));
const historical=M.makeSession(state,M.slots[0],date);
M.mark(state,historical,question,'wrong');
assert.equal(state.knowledge[key].last,M.shift(date,1),'Backfilled answers must not replace newer review state');
const fresh=M.initial();
for(let day=0;day<6;day++){
  const session=M.makeSession(fresh,M.slots[0],M.shift(date,day));
  session.questions=Array.from({length:5},(_,index)=>({...session.questions[0],id:'proof-'+day+'-'+index}));
  fresh.sessions[session.id]=session;
  for(const question of session.questions)M.mark(fresh,session,question,question.answer);
}
assert.equal(M.trainingPhase(fresh,'en',M.shift(date,35)),1);
assert.equal(M.trainingPhase(fresh,'ja',M.shift(date,35)),0);
const empty=M.initial();
assert.doesNotThrow(()=>M.validateBackup(empty));
assert.throws(()=>M.validateBackup({...empty,checkins:[date]}));
assert.throws(()=>M.validateBackup({...empty,knowledge:{bad:{}}}));
empty.external.push({date,lang:'en',courseId:'EXTERNAL-01',answer:'自报诊断',weakness:'listen'});
assert.equal(M.focus(empty,'en',date).skill,'listen');
assert.equal(M.statistics(empty,[date]).en.total,0,'External ungraded records must not create scores');
empty.checkins=[date,M.shift(date,1),M.shift(date,3)];
assert.equal(M.streak(empty,M.shift(date,1)),2);
assert.equal(M.streak(empty,M.shift(date,3)),1);
console.log('PASS: 120-minute budgets, calendar, baseline, course keys, grading, review intervals, history protection, evidence gates, backup validation, separate language statistics, streaks');
